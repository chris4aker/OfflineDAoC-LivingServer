"""Writes EraBotNameWords.cs: the words a bot name must not be.

A player's chat that names a bot is taken as said to that bot, and the name is cut out of it
(AutonomousBotChatCoordinator, AutonomousChatThreads.WithoutName). A bot called "Axe" or "First"
would catch "first time here?". So a generated name is never an English word or a word the bots
themselves say. Sources: every word in the chat corpus, and every English word at least as common as "hellfire"
(Zipf frequency 2.7 or more in the wordfreq package, about 40,000 words). Run from the repository root after the corpus changes:

    pip install wordfreq
    python3 source/tools/make_era_name_words.py
"""
import json
import pathlib
import re

from wordfreq import iter_wordlist, zipf_frequency

ROOT = pathlib.Path(__file__).resolve().parents[1]
CORPUS = ROOT / "server/GameServer/bots/autonomous/data/chat/corpus.json"
OUT = ROOT / "server/GameServer/bots/autonomous/EraBotNameWords.cs"
MIN_ZIPF = 2.7


def words(text):
    return re.findall(r"[a-z]+", re.sub(r"\{[^}]*\}", " ", text.lower()))


def main():
    corpus = json.loads(CORPUS.read_text(encoding="utf-8"))
    found = set()
    for line in corpus["lines"]:
        found.update(words(line["text"]))
    for scene in corpus["scenes"]:
        for beat in scene.get("beats", []):
            for variant in beat.get("variants", []) if isinstance(beat, dict) else []:
                found.update(words(variant if isinstance(variant, str) else variant.get("text", "")))
    for w in iter_wordlist("en"):
        if zipf_frequency(w, "en") < MIN_ZIPF:
            break
        if w.isalpha() and w.isascii():
            found.add(w)
    kept = sorted(w for w in found if 3 <= len(w) <= 16)
    rows = []
    row = ""
    for w in kept:
        if len(row) + len(w) + 1 > 110:
            rows.append(row)
            row = ""
        row += (" " if row else "") + w
    rows.append(row)
    body = "\n".join(f'        "{r} " +' for r in rows)
    OUT.write_text(
        "// Generated by source/tools/make_era_name_words.py: the words a generated bot name must not be.\n"
        "// Linked into the launcher.\n"
        "namespace OfflineDaoc.Shared;\n\n"
        "public static partial class EraBotNames\n{\n"
        "    private const string WordList =\n" + body + "\n        \"\";\n}\n",
        encoding="utf-8", newline="\n")
    print(f"{len(kept)} words -> {OUT}")


if __name__ == "__main__":
    main()
