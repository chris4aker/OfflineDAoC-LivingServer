#!/usr/bin/env python3
"""Weekly upstream watch: list the commits each watched repo gained since its last reviewed commit.

Reads .github/upstream-watch.json, clones each repo (blobless, so it is quick), and writes a Markdown report of the new
commits since `reviewed`, grouped into likely gameplay fixes, likely features and the rest by their message and paths.
The workflow (.github/workflows/upstream-watch.yml) posts the report as one open issue per repo, updated in place.

    python3 source/tools/upstream_watch.py --out report-dir [--config .github/upstream-watch.json]

No network writes here; the workflow owns the issue. Exit 0 always (an unreachable repo is reported, not fatal).
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

FIX = re.compile(r"\b(fix|fixes|fixed|bug|crash|exception|null|leak|correct|wrong|broken|regression|exploit|desync)\b", re.I)
FEATURE = re.compile(r"\b(add|adds|added|implement|new|support|feature|introduce)\b", re.I)
MAX_BODY = 60000
GAMEPLAY_PATH = re.compile(
    r"(spell|style|combat|attack|damage|keep|relic|rvr|guard|brain|ai/|pathing|navmesh|quest|craft|item|loot|xp|"
    r"experience|effect|ability|realm|npc|mob|siege|stealth|group|zone|region|property)", re.I)


def git(args: list[str], cwd: Path | None = None) -> str:
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True).stdout


def classify(subject: str, paths: list[str]) -> str:
    gameplay = any(GAMEPLAY_PATH.search(p) for p in paths) or bool(GAMEPLAY_PATH.search(subject))
    if FIX.search(subject):
        return "fix" if gameplay else "other-fix"
    if FEATURE.search(subject) and gameplay:
        return "feature"
    return "other"


def commits_since(url: str, branch: str, reviewed: str, work: Path) -> tuple[str, list[dict]]:
    # One clone per repo and branch: two entries may watch two branches of one repo.
    dest = work / re.sub(r"\W+", "-", f"{url}-{branch}")
    git(["clone", "--quiet", "--filter=blob:none", "--no-checkout", "--branch", branch, url, str(dest)])
    head = git(["rev-parse", "HEAD"], dest).strip()
    rng = f"{reviewed}..HEAD" if reviewed else "HEAD~50..HEAD"
    log = git(["log", "--no-merges", "--name-only", "--format=%x1e%H%x09%ad%x09%an%x09%s", "--date=short", rng], dest)
    out: list[dict] = []
    for block in log.split("\x1e")[1:]:
        lines = [l for l in block.splitlines() if l.strip()]
        sha, date, author, subject = lines[0].split("\t", 3)
        paths = lines[1:]
        out.append({"sha": sha, "date": date, "author": author, "subject": subject, "paths": paths,
                    "kind": classify(subject, paths)})
    return head, out


def report(repo: dict, head: str, commits: list[dict]) -> str:
    url, reviewed = repo["url"], repo.get("reviewed", "")
    lines = [f"**{repo['name']}**: {len(commits)} new commits on `{repo['branch']}` since the last review "
             f"(`{reviewed[:9]}`), up to `{head[:9]}`.", "",
             "Generated by the weekly upstream watch (`source/tools/upstream_watch.py`). The grouping is by keywords "
             "only; a person or agent decides what to port (see docs/UPSTREAM-WATCH.md), then moves `reviewed` in "
             "`.github/upstream-watch.json` forward.", ""]
    titles = {"fix": "Likely gameplay fixes", "feature": "Likely gameplay features",
              "other-fix": "Other fixes (tools, build, non-gameplay)", "other": "Everything else"}
    for kind in ("fix", "feature", "other-fix", "other"):
        group = [c for c in commits if c["kind"] == kind]
        if not group:
            continue
        lines.append(f"### {titles[kind]} ({len(group)})")
        for c in group:
            shown = ", ".join(p.split("/")[-1] for p in c["paths"][:4]) + (" ..." if len(c["paths"]) > 4 else "")
            subject = c["subject"] if len(c["subject"]) <= 140 else c["subject"][:137] + "..."
            lines.append(f"- [`{c['sha'][:9]}`]({url}/commit/{c['sha']}) {c['date']} {subject}"
                         + (f" ({shown})" if shown else ""))
        lines.append("")
    if not commits:
        lines.append("Nothing new since the last review.")
    text = "\n".join(lines)
    if len(text) > MAX_BODY:  # GitHub caps an issue body at 65,536 characters
        cut = text[:MAX_BODY].rsplit("\n", 1)[0]
        text = cut + f"\n\n... cut at {MAX_BODY} characters; run `source/tools/upstream_watch.py` locally for the full list."
    return text


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--config", default=".github/upstream-watch.json")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    config = json.loads(Path(args.config).read_text(encoding="utf-8"))
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    summary = []
    with tempfile.TemporaryDirectory() as tmp:
        for repo in config["repos"]:
            slug = re.sub(r"\W+", "-", repo["name"])
            try:
                head, commits = commits_since(repo["url"], repo["branch"], repo.get("reviewed", ""), Path(tmp))
                text = report(repo, head, commits)
                count = len(commits)
            except subprocess.CalledProcessError as err:
                text = f"**{repo['name']}**: the watch could not read {repo['url']} ({(err.stderr or '').strip()[:300]})."
                count = -1
            (out / f"{slug}.md").write_text(text + "\n", encoding="utf-8")
            summary.append({"name": repo["name"], "slug": slug, "count": count})
    (out / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(json.dumps(summary))
    return 0


if __name__ == "__main__":
    sys.exit(main())
