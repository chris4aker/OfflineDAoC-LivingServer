"""The local stack's configs: Loki, Grafana's provisioning and the Windows portable templates (issue #628).

kit.py --write writes them; --check fails when they are stale. Two layouts:
- tools/grafana/local/: the docker-compose stack. Inside the containers the services listen on their network;
  docker-compose.yml publishes each port on 127.0.0.1 only.
- tools/grafana/windows/templates/: the Windows portable setup (setup.ps1). Every service listens on 127.0.0.1, and
  every path is under the observability folder: setup.ps1 replaces @@ROOT@@ with that folder (forward slashes).
"""
from __future__ import annotations

from dashboards import DATASOURCE_UID, FOLDER_TITLE, FOLDER_UID

ROOT = "@@ROOT@@"
RETENTION = "336h"  # 14 days


def loki_config(bind: str, data: str) -> str:
    return f"""# GENERATED by tools/grafana/kit.py (issue #628). Single-process Loki on local disk, {RETENTION} retention.
auth_enabled: false

server:
  http_listen_address: {bind}
  http_listen_port: 3100
  grpc_listen_address: {bind}
  grpc_listen_port: 9096
  log_level: warn

common:
  instance_addr: 127.0.0.1
  path_prefix: {data}
  storage:
    filesystem:
      chunks_directory: {data}/chunks
      rules_directory: {data}/rules
  replication_factor: 1
  ring:
    kvstore:
      store: inmemory

schema_config:
  configs:
    - from: 2024-01-01
      store: tsdb
      object_store: filesystem
      schema: v13
      index:
        prefix: index_
        period: 24h

limits_config:
  retention_period: {RETENTION}
  reject_old_samples: true
  reject_old_samples_max_age: {RETENTION}
  max_query_lookback: {RETENTION}

compactor:
  working_directory: {data}/compactor
  retention_enabled: true
  delete_request_store: filesystem

ruler:
  storage:
    type: local
    local:
      directory: {data}/rules

analytics:
  reporting_enabled: false
"""


def datasource(url: str) -> str:
    return f"""# GENERATED by tools/grafana/kit.py (issue #628).
apiVersion: 1
datasources:
  - name: Offline DAoC Loki
    uid: {DATASOURCE_UID}
    type: loki
    access: proxy
    url: {url}
    isDefault: true
    editable: false
"""


def dashboard_provider(path: str) -> str:
    return f"""# GENERATED by tools/grafana/kit.py (issue #628). allowUiUpdates lets `gcx resources push` update them; the
# files win again when they change (re-run the setup or copy the new files).
apiVersion: 1
providers:
  - name: offlinedaoc
    folder: {FOLDER_TITLE}
    folderUid: {FOLDER_UID}
    type: file
    allowUiUpdates: true
    updateIntervalSeconds: 60
    options:
      path: {path}
"""


def grafana_ini_windows() -> str:
    return f"""; GENERATED by tools/grafana/kit.py (issue #628). Grafana for the Windows portable setup: 127.0.0.1 only,
; every path under the observability folder, no sign-up, no anonymous access, no calls home.
[server]
http_addr = 127.0.0.1
http_port = 3000
domain = 127.0.0.1
root_url = http://127.0.0.1:3000/

[paths]
data = {ROOT}/data/grafana
logs = {ROOT}/logs/grafana
plugins = {ROOT}/data/grafana/plugins
provisioning = {ROOT}/grafana-provisioning

[security]
admin_user = admin
admin_password = $__file{{{ROOT}/admin-password.txt}}
disable_gravatar = true
cookie_samesite = strict

[users]
allow_sign_up = false
allow_org_create = false

[auth.anonymous]
enabled = false

[analytics]
reporting_enabled = false
check_for_updates = false
check_for_plugin_updates = false
feedback_links_enabled = false

[news]
news_feed_enabled = false

[plugins]
preinstall_disabled = true

[log]
mode = file
"""


def outputs() -> dict[str, str]:
    """Relative path (under tools/grafana) -> file text."""
    return {
        "local/loki.yaml": loki_config("0.0.0.0", "/loki"),
        "local/provisioning/datasources/loki.yaml": datasource("http://loki:3100"),
        "local/provisioning/dashboards/offlinedaoc.yaml": dashboard_provider("/var/lib/grafana/dashboards/offlinedaoc"),
        "windows/templates/loki.yaml": loki_config("127.0.0.1", f"{ROOT}/data/loki"),
        "windows/templates/grafana.ini": grafana_ini_windows(),
        "windows/templates/datasource.yaml": datasource("http://127.0.0.1:3100"),
        "windows/templates/dashboards.yaml": dashboard_provider(f"{ROOT}/dashboards"),
    }
