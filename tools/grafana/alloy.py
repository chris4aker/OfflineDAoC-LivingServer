"""The Grafana Alloy pipeline: generated from the row catalog, and replayed in Python by the tests (issue #628).

generate() writes tools/grafana/alloy/config.alloy. Filter reads that file back (the selectors and expressions as they
ship) and applies them to lines in the order Alloy does, so the tests check the config itself, not a copy of its rules.

The pipeline, stage by stage:
1. Split the server's file layout (`MM/dd HH:mm:ss | LVL | logger | message`) and keep only the message. A line that
   is not in that layout (an exception's stack trace, a wrapped line) is dropped.
2. Drop every message that does not start with an allowlisted row marker followed by a space or the end.
3. Inside the allowed rows, remove the fields that could carry a name or free text, per row (privacy.py), and blank
   JSON values whose key names a person. Redact anything shaped like an IPv4 address.
4. Labels: job, log (server or detail), row and realm (Albion, Midgard, Hibernia or other). The file path label is
   dropped: on Windows it holds the user's folder name. build comes from OFFLINEDAOC_BUILD.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path

LINE_LAYOUT = r"^(?P<ts>\d\d/\d\d \d\d:\d\d:\d\d) \| (?P<level>[A-Z]{3}) \| (?P<logger>[^|]*?) \| (?P<msg>.*)$"
IPV4 = r"\b(\d{1,3}(?:\.\d{1,3}){3})\b"
JOB = "offlinedaoc"


def _q(text: str) -> str:
    """An Alloy string literal (Alloy strings escape like JSON's)."""
    return json.dumps(text, ensure_ascii=True)


def _alternation(names) -> str:
    return "(?:" + "|".join(sorted(names)) + ")"


def _selector(op: str, regex: str) -> str:
    if '"' in regex or "\\" in regex:
        raise ValueError("a line-filter regex here has no quotes or backslashes")
    return '{job="' + JOB + '"} ' + op + ' "' + regex + '"'


def field_drop_regex(keys) -> str:
    """Matches ` key=value` and ` key="quoted value"` for the given keys; the whole pair is the capture."""
    return "( " + _alternation(keys) + r'=(?:"(?:[^"\\]|\\.)*"|[^ ]*))'


def json_drop_regex(keys) -> str:
    """Matches the value of `"key":"..."` or `"key":[...]` for the given keys; the value is the capture."""
    return '"' + _alternation(keys) + r'":("(?:[^"\\]|\\.)*"|\[[^\]]*\])'


REALM_TEMPLATE = ('{{ with .realm_raw }}{{ if or (eq . "Albion") (eq . "1") }}Albion'
                  '{{ else if or (eq . "Midgard") (eq . "2") }}Midgard'
                  '{{ else if or (eq . "Hibernia") (eq . "3") }}Hibernia{{ else }}other{{ end }}{{ end }}')


def generate(allowed: list[str], drops: dict[frozenset, list[str]], json_keys: list[str]) -> str:
    """allowed: the shipped row markers; drops: a set of field keys -> the rows that drop exactly those."""
    out: list[str] = []
    w = out.append
    w("// GENERATED by tools/grafana/kit.py --write from the server code (issue #628). Do not edit: run the kit.")
    w("// Offline DAoC Living Server -> Loki. Ships only allowlisted rows, minus fields that could carry a name.")
    w("// Environment: OFFLINEDAOC_LOGS (the server's logs folder, required), LOKI_URL (default the local Loki),")
    w("// LOKI_USERNAME / LOKI_PASSWORD (Grafana Cloud only), OFFLINEDAOC_BUILD (a build label), OFFLINEDAOC_TZ")
    w("// (the server PC's IANA time zone; default the local one). Nothing secret is written in this file.")
    w("")
    w('local.file_match "offlinedaoc" {')
    w("  path_targets = [")
    w('    {"__path__" = file.path_join(sys.env("OFFLINEDAOC_LOGS"), "server*.log"), "log" = "server", "job" = "' + JOB + '"},')
    w('    {"__path__" = file.path_join(sys.env("OFFLINEDAOC_LOGS"), "detail*.log"), "log" = "detail", "job" = "' + JOB + '"},')
    w("  ]")
    w('  sync_period = "10s"')
    w("}")
    w("")
    w('loki.source.file "offlinedaoc" {')
    w("  targets    = local.file_match.offlinedaoc.targets")
    w("  forward_to = [loki.process.offlinedaoc.receiver]")
    w("}")
    w("")
    w('loki.process "offlinedaoc" {')
    w("  forward_to = [loki.write.offlinedaoc.receiver]")
    w("")
    w("  // 1. The message only; a line outside the server's layout is dropped.")
    w("  stage.regex {")
    w("    expression = " + _q(LINE_LAYOUT))
    w("  }")
    w("  stage.template {")
    w('    source   = "layout"')
    w("    template = " + _q("{{ if .ts }}ok{{ else }}no{{ end }}"))
    w("  }")
    w("  stage.drop {")
    w('    source              = "layout"')
    w('    value               = "no"')
    w('    drop_counter_reason = "not_a_server_line"')
    w("  }")
    w("  stage.output {")
    w('    source = "msg"')
    w("  }")
    w("")
    w(f"  // 2. The allowlist: {len(allowed)} rows (docs/LOG-ROWS.md). Anything else is dropped.")
    w("  stage.match {")
    w("    selector            = " + _q(_selector("!~", "^" + _alternation(allowed) + "(?: |$)")))
    w('    action              = "drop"')
    w('    drop_counter_reason = "not_allowlisted"')
    w("  }")
    w("")
    w("  // 3. Fields that could carry a name or free text, per row (docs/LOG-ROWS.md, \"Dropped\").")
    for keys, rows in sorted(drops.items(), key=lambda kv: (sorted(kv[0]), kv[1])):
        if not keys:
            continue
        w("  stage.match {")
        w("    selector = " + _q(_selector("|~", "^" + _alternation(rows) + "(?: |$)")))
        w("    stage.replace {")
        w("      expression = " + _q(field_drop_regex(keys)))
        w('      replace    = ""')
        w("    }")
        w("  }")
    w("  stage.replace {")
    w("    expression = " + _q(json_drop_regex(json_keys)))
    w("    replace    = " + _q('"-"'))
    w("  }")
    w("  stage.replace {")
    w("    expression = " + _q(IPV4))
    w('    replace    = "-"')
    w("  }")
    w("")
    w("  // 4. Labels: row and realm (low cardinality), the time from the line.")
    w("  stage.regex {")
    w("    expression = " + _q(r"^(?P<row>[A-Z][A-Z0-9_]*)"))
    w("  }")
    w("  stage.logfmt {")
    w('    mapping = {"realm_raw" = "realm"}')
    w("  }")
    w("  stage.template {")
    w('    source   = "realm"')
    w("    template = " + _q(REALM_TEMPLATE))
    w("  }")
    w("  stage.labels {")
    w('    values = {"row" = "", "realm" = ""}')
    w("  }")
    w("  stage.timestamp {")
    w('    source   = "ts"')
    w('    format   = "01/02 15:04:05"')
    w('    location = coalesce(sys.env("OFFLINEDAOC_TZ"), "Local")')
    w("  }")
    w("  stage.label_drop {")
    w('    values = ["filename"]')
    w("  }")
    w("}")
    w("")
    w('loki.write "offlinedaoc" {')
    w('  external_labels = {"build" = coalesce(sys.env("OFFLINEDAOC_BUILD"), "unset")}')
    w("  endpoint {")
    w('    url = coalesce(sys.env("LOKI_URL"), "http://127.0.0.1:3100/loki/api/v1/push")')
    w("    basic_auth {")
    w('      username = sys.env("LOKI_USERNAME")')
    w('      password = sys.env("LOKI_PASSWORD")')
    w("    }")
    w("  }")
    w("}")
    return _alloy_fmt(out)


def _alloy_fmt(lines: list[str]) -> str:
    """Alloy's own layout (what `alloy fmt` prints): tabs, a blank line between blocks, no blank before a close."""
    tabbed = [re.sub(r"^((?:  )+)", lambda m: "\t" * (len(m.group(1)) // 2), line) for line in lines]
    out: list[str] = []
    for i, line in enumerate(tabbed):
        nxt = tabbed[i + 1] if i + 1 < len(tabbed) else None
        if line == "" and (nxt is None or nxt.strip() == "}" or (out and out[-1] == "")):
            continue
        opener = line.endswith(" {") and "=" not in line
        if opener and out and out[-1] != "" and not out[-1].endswith("{") and not out[-1].lstrip().startswith("//"):
            out.append("")
        out.append(line)
        if line.strip() == "}" and line.startswith("\t") and nxt is not None and nxt.strip() not in ("}", "") \
                and not nxt.lstrip().startswith("//"):
            out.append("")
    return "\n".join(out) + "\n"


# ---- The Python replay of the shipped config ------------------------------------------------------------------------

_STRING = r'"(?:[^"\\]|\\.)*"'


def _unq(literal: str) -> str:
    return json.loads(literal)


def _line_filter(selector: str) -> tuple[str, re.Pattern]:
    m = re.fullmatch(r'\{job="' + JOB + r'"\} (\|~|!~) "([^"\\]*)"', selector)
    if not m:
        raise ValueError(f"unexpected selector: {selector}")
    return m.group(1), re.compile(m.group(2))


@dataclass
class Shipped:
    line: str
    labels: dict[str, str] = field(default_factory=dict)


class Filter:
    """The config's stages, read from the .alloy text, applied as Alloy applies them."""

    def __init__(self, config_text: str):
        body = config_text[config_text.index('loki.process "offlinedaoc"'):config_text.index('loki.write "offlinedaoc"')]
        self.layout = re.compile(_unq(re.search(r"stage\.regex \{\s*expression = (" + _STRING + ")", body).group(1)))
        allow = re.search(r'stage\.match \{\s*selector\s*= (' + _STRING + r')\s*action\s*= "drop"', body)
        self.allow_op, self.allow = _line_filter(_unq(allow.group(1)))
        assert self.allow_op == "!~"
        self.field_drops: list[tuple[re.Pattern, re.Pattern]] = []
        for m in re.finditer(r'stage\.match \{\s*selector = (' + _STRING + r')\s*stage\.replace \{\s*expression = ('
                             + _STRING + r')\s*replace\s*= ""', body):
            op, sel = _line_filter(_unq(m.group(1)))
            assert op == "|~"
            self.field_drops.append((sel, re.compile(_unq(m.group(2)))))
        tail = body[body.rindex("stage.match"):]
        replaces = re.findall(r'^\tstage\.replace \{\s*expression = (' + _STRING + r')\s*replace\s*= (' + _STRING + ')',
                              tail, re.M)
        self.global_replaces = [(re.compile(_unq(e)), _unq(r)) for e, r in replaces]
        if len(self.global_replaces) != 2:
            raise ValueError("expected the JSON and IPv4 replace stages")

    @staticmethod
    def _replace(pattern: re.Pattern, line: str, value: str) -> str:
        """Alloy's stage.replace: each capture group of each match becomes value."""
        out, last = [], 0
        for m in pattern.finditer(line):
            for g in range(1, (pattern.groups or 0) + 1):
                if m.start(g) < 0:
                    continue
                out.append(line[last:m.start(g)])
                out.append(value)
                last = m.end(g)
        out.append(line[last:])
        return "".join(out)

    def apply(self, raw: str, log: str = "server") -> Shipped | None:
        m = self.layout.match(raw)
        if not m:
            return None
        line = m.group("msg")
        if self.allow.search(line):  # the selector is `!~`: a line that does not match is dropped
            pass
        else:
            return None
        for sel, expr in self.field_drops:
            if sel.search(line):
                line = self._replace(expr, line, "")
        for expr, value in self.global_replaces:
            line = self._replace(expr, line, value)
        labels = {"job": JOB, "log": log, "row": re.match(r"^([A-Z][A-Z0-9_]*)", line).group(1)}
        realm = re.search(r'(?:^| )realm=("(?:[^"\\]|\\.)*"|[^ ]*)', line)
        if realm:
            value = realm.group(1).strip('"')
            labels["realm"] = {"Albion": "Albion", "1": "Albion", "Midgard": "Midgard", "2": "Midgard",
                               "Hibernia": "Hibernia", "3": "Hibernia"}.get(value, "other") if value else ""
            if not labels["realm"]:
                del labels["realm"]
        return Shipped(line, labels)


def load_filter(path: Path) -> Filter:
    return Filter(path.read_text(encoding="utf-8"))
