#!/usr/bin/env python3
"""The Grafana kit's generator and check (issue #628).

    python3 tools/grafana/kit.py --write               # regenerate the dashboards and the stack files (commit these)
    python3 tools/grafana/kit.py --check               # CI and tools/check.py: fail when they are stale or name a bad row
    python3 tools/grafana/kit.py --write --generated   # also docs/LOG-ROWS.md and the Alloy config (main's workflow)
    python3 tools/grafana/kit.py --check --generated   # also fail when those two are stale

Issue #817 (owner decision 59A): docs/LOG-ROWS.md and tools/grafana/alloy/config.alloy are generated on main, not in
pull requests. Every pull request that added a row conflicted with the next one in those two files. A pull request
doesn't commit them (tools/grafana/generated_guard.py fails one that does); --check still builds them, so a row the kit
can't read fails, but it doesn't compare them with the committed copies. After each merge, the generated-files
workflow (.github/workflows/generated-files.yml) runs --write --generated and proposes the result in the
bot/generated-files pull request.

From the server code (rows.py) and the reviewed policy (row-policy.json, pending-rows.json) it writes:
- docs/LOG-ROWS.md: every structured row, its log file, writing sites, fields, the fields the filter drops, and
  whether it ships;
- tools/grafana/alloy/config.alloy: the allowlist and the per-row field drops (alloy.py);
- tools/grafana/resources/ (gcx manifests) and tools/grafana/provisioning/dashboards/ (file provisioning).

--check also fails when a dashboard, the policy or the pending file names a row that is neither in code nor
pending, when a dashboard reads a field the row doesn't have or the filter drops, or when the allowlist names a row
it shouldn't. A row added to the server code makes main's catalog stale until the generated-files pull request lands.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import alloy  # noqa: E402
import dashboards  # noqa: E402
import privacy  # noqa: E402
import rows as rowscan  # noqa: E402
import stack  # noqa: E402

REPO = HERE.parents[1]
CATALOG = Path("docs/LOG-ROWS.md")
ALLOY_CONFIG = Path("tools/grafana/alloy/config.alloy")
# Written and compared only with --generated: main's workflow regenerates them after each merge (#817).
GENERATED_ON_MAIN = (CATALOG, ALLOY_CONFIG)


class Kit:
    def __init__(self, repo: Path):
        self.repo = repo
        self.rows = rowscan.scan(repo)
        self.policy = privacy.load_policy(repo / "tools/grafana/row-policy.json", repo / "tools/grafana/pending-rows.json")
        self.pending = {k: v for k, v in self.policy.pending.items() if k not in self.rows}
        self.ship: dict[str, bool] = {}
        self.why_not: dict[str, str] = {}
        self.drops: dict[str, dict[str, str]] = {}
        self.marker_only: set[str] = set()  # pending rows with no known fields: only the marker and realm ship
        for marker, row in self.rows.items():
            ok, why = privacy.shipped(row, self.policy)
            self.ship[marker], self.why_not[marker] = ok, why
            self.drops[marker] = privacy.dropped_fields(row, self.policy) if ok else {}
        for marker, p in self.pending.items():
            ok = marker not in self.policy.exclude
            self.ship[marker], self.why_not[marker] = ok, "" if ok else self.policy.exclude[marker]
            if marker in self.policy.name_free:
                self.drops[marker] = {}
            elif p.get("fields") is None:
                # Fields not known yet: nothing but the marker and the realm ships (fail closed).
                self.marker_only.add(marker)
                self.drops[marker] = {"*": "pending row, fields not known yet: only the marker and realm ship"}
            else:
                fake = rowscan.Row(marker, fields={k: set() for k in p["fields"]})
                self.drops[marker] = privacy.dropped_fields(fake, self.policy)

    def fields_of(self, marker: str):
        if marker in self.rows:
            return set(self.rows[marker].fields)
        f = self.pending.get(marker, {}).get("fields")
        return None if f is None else set(f)

    def allowed(self) -> list[str]:
        return sorted(m for m, ok in self.ship.items() if ok)

    def alloy_config(self) -> str:
        groups: dict[frozenset, list[str]] = {}
        for marker in self.allowed():
            if marker not in self.marker_only:
                groups.setdefault(frozenset(self.drops[marker]), []).append(marker)
        return alloy.generate(self.allowed(), groups, self.policy.json_keys,
                              sorted(m for m in self.marker_only if self.ship[m]))

    def catalog(self) -> str:
        out: list[str] = []
        w = out.append
        shipped = self.allowed()
        w("# Log rows")
        w("")
        w("GENERATED by `python3 tools/grafana/kit.py --write` from the server code (issue #628). Do not edit by hand:")
        w("main's generated-files workflow rewrites it after each merge (issue #817), so a pull request never commits it.")
        w("")
        w("A row is one log message that starts with a stable marker and carries `key=value` fields (or JSON after the")
        w("marker). The server writes them to `runtime/server/logs/server.log` or `detail.log` (logconfig.xml); the say")
        w("gate's rows go to `session-chat.log`. [GRAFANA.md](GRAFANA.md) charts them; the Alloy pipeline ships only the")
        w("rows marked **ships**, and removes the fields listed under *Dropped* (they could carry a player's, a")
        w("bot's, a guild's or an account's name, or free text). How a field is judged: `tools/grafana/privacy.py`;")
        w("the reviewed exceptions: `tools/grafana/row-policy.json`.")
        w("")
        w(f"- Rows in code: **{len(self.rows)}**; pending (#625, not on main yet): **{len(self.pending)}**; shipped by "
          f"the pipeline: **{len(shipped)}**.")
        w("- *Frequency* is filled where the code or the policy states it; `-` means per event, not stated.")
        w("- *Written in* names the files (search them for the marker); *Meaning* is the comment above the first writing site,")
        w("  cut to its first sentence.")
        w("")
        if self.pending:
            w("## Pending rows")
            w("")
            w("| Row | Issue | Branch | Log | Fields | Frequency | Meaning |")
            w("|---|---|---|---|---|---|---|")
            for marker, p in sorted(self.pending.items()):
                fields = ", ".join(f"`{f}`" for f in p["fields"]) if p.get("fields") else ("not on a branch yet (spec only); "
                                                                                         "ships its marker and realm only")
                w(f"| `{marker}` | pending #{p['issue']} | `{p['branch']}` | {p['log']} | {fields} | {p['frequency']} | "
                  f"{p['meaning']} |")
            w("")
        w("## Rows in code")
        w("")
        w("| Row | Log | Ships | Written in | Fields | Dropped | Frequency | Meaning |")
        w("|---|---|---|---|---|---|---|---|")
        for marker, row in self.rows.items():
            # Files, not line numbers: an edit elsewhere in a file must not make the catalog stale.
            files = list(dict.fromkeys(s.path.removeprefix("source/server/GameServer/") for s in row.sites))
            sites = "<br>".join(f"`{f}`" for f in files[:3])
            if len(files) > 3:
                sites += f"<br>+{len(files) - 3} more"
            fields = "JSON" if row.json and not row.fields else ", ".join(f"`{k}`" for k in sorted(row.fields)) or "-"
            if row.json and row.fields:
                fields = "JSON, " + fields
            dropped = ", ".join(f"`{k}`" for k in sorted(self.drops[marker])) or "-"
            ships = "**ships**" if self.ship[marker] else f"no: {self.why_not[marker]}"
            freq = self.policy.frequency.get(marker, "-")
            meaning = (row.comment or "-").replace("\n", " ")
            w(f"| `{marker}` | {row.log} | {ships} | {sites} | {fields} | {dropped} | {freq} | {meaning} |")
        return "\n".join(out) + "\n"

    def outputs(self) -> dict[Path, str]:
        out = {CATALOG: self.catalog(), ALLOY_CONFIG: self.alloy_config()}
        for rel, text in {**dashboards.outputs(), **stack.outputs()}.items():
            out[Path("tools/grafana") / rel] = text
        return out

    def problems(self) -> list[str]:
        errors: list[str] = []
        known = set(self.rows) | set(self.pending)
        for section, names in (("exclude_rows", self.policy.exclude), ("name_free_rows", self.policy.name_free),
                               ("extra_drop", self.policy.extra_drop), ("keep", self.policy.keep),
                               ("frequency", self.policy.frequency)):
            for marker in names:
                if marker not in known:
                    errors.append(f"row-policy.json {section} names {marker}, which is neither in code nor pending")
        for marker, p in self.policy.pending.items():
            if p.get("issue") is None or not p.get("branch"):
                errors.append(f"pending-rows.json: {marker} needs an issue and a branch")
        for d in dashboards.DASHBOARDS:
            for panel in d.panels:
                for marker in panel.rows:
                    if marker not in known:
                        errors.append(f"dashboard {d.slug} / {panel.title!r}: row {marker} is neither in code nor pending")
                        continue
                    if not self.ship.get(marker):
                        errors.append(f"dashboard {d.slug} / {panel.title!r}: row {marker} is not shipped by the filter")
                    if f'"{marker}"' not in panel.expr and marker not in panel.expr:
                        errors.append(f"dashboard {d.slug} / {panel.title!r}: query does not read {marker}")
                    fields = self.fields_of(marker)
                    for f in panel.fields:
                        if marker in self.marker_only and f != "realm":
                            errors.append(f"dashboard {d.slug} / {panel.title!r}: {marker}'s fields are not known yet; "
                                          f"only its marker and realm ship, not {f}")
                            continue
                        if fields is not None and f not in fields:
                            errors.append(f"dashboard {d.slug} / {panel.title!r}: {marker} has no field {f}")
                        if f in self.drops.get(marker, {}):
                            errors.append(f"dashboard {d.slug} / {panel.title!r}: the filter drops {marker} {f}")
        for marker in self.allowed():
            if marker not in known:
                errors.append(f"the allowlist names {marker}, which is neither in code nor pending")
        # #690: a pending entry for a row the scanner finds is an error, not a note. Its hand-copied fields would hide what
        # the code really writes (BG_POPULATION, CAST_INTERRUPT and BG_TARGET_PICK sat pending on main that way).
        for marker in self.policy.pending:
            if marker in self.rows:
                errors.append(f"pending-rows.json: {marker} is in code now; remove its entry")
        return errors

    def notes(self) -> list[str]:
        return []


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    ap.add_argument("--generated", action="store_true",
                    help="also write or compare docs/LOG-ROWS.md and the Alloy config (generated on main, #817)")
    ap.add_argument("--repo", type=Path, default=REPO)
    args = ap.parse_args(argv)
    repo = args.repo.resolve()
    kit = Kit(repo)
    if len(kit.rows) < 100:
        print(f"only {len(kit.rows)} rows found under {repo / 'source/server'}: the scan is broken", file=sys.stderr)
        return 1
    errors = kit.problems()
    built = kit.outputs()  # every file is built, so a row the kit can't read fails in any mode
    outputs = built if args.generated else {rel: t for rel, t in built.items() if rel not in GENERATED_ON_MAIN}
    for note in kit.notes():
        print(f"note: {note}")
    if args.write:
        for rel, text in outputs.items():
            path = repo / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
        generated = {repo / rel for rel in built}
        for folder in ("tools/grafana/resources/dashboards", "tools/grafana/provisioning/dashboards"):
            for old in (repo / folder).glob("*.json"):
                if old not in generated:
                    old.unlink()
        print(f"wrote {len(outputs)} files: {len(kit.rows)} rows in code, {len(kit.pending)} pending, "
              f"{len(kit.allowed())} shipped")
    else:
        for rel, text in outputs.items():
            path = repo / rel
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                errors.append(f"{rel.as_posix()} is stale: run python3 tools/grafana/kit.py --write"
                              + (" --generated" if rel in GENERATED_ON_MAIN else ""))
        if not args.generated:
            for rel in GENERATED_ON_MAIN:
                path = repo / rel
                if not path.exists() or path.read_text(encoding="utf-8") != built[rel]:
                    print(f"note: {rel.as_posix()} differs from this branch's code; main regenerates it after the merge "
                          "(#817): don't commit it")
        generated = {(repo / rel).resolve() for rel in built}
        for folder in ("tools/grafana/resources/dashboards", "tools/grafana/provisioning/dashboards"):
            for extra in (repo / folder).glob("*.json"):
                if extra.resolve() not in generated:
                    errors.append(f"{extra.relative_to(repo).as_posix()} is not generated: delete it or add it to dashboards.py")
    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    if errors:
        return 1
    if args.check:
        print(f"Grafana kit up to date: {len(kit.rows)} rows in code, {len(kit.pending)} pending, "
              f"{len(kit.allowed())} shipped, {sum(len(d.panels) for d in dashboards.DASHBOARDS)} panels.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
